import json
import re
import sqlite3
import urllib.request

# Configuration for your local Ollama model
OLLAMA_MODEL = "llama3.2:1b"


def extract_clean_name(user_input):
  """Extracts clean name from inputs like 'Fatima' or 'My name is Fatima'."""
  text = user_input.strip()
  match = re.search(
      r"(?:my name is|i am|i'm)\s+([a-zA-Z]+)", text, re.IGNORECASE
  )
  if match:
    return match.group(1).capitalize()
  words = text.split()
  return words[0].capitalize() if words else "Learner"


def get_curriculum_from_db(country, topic="Computer System"):
  """Pulls definition and keywords from SQLite database."""
  conn = sqlite3.connect("subject.db")
  cursor = conn.cursor()

  cursor.execute(
      """
        SELECT category, content 
        FROM computer_studies 
        WHERE country = ? AND topic = ?
    """,
      (country, topic),
  )
  rows = cursor.fetchall()
  conn.close()

  definition = ""
  keywords = []

  for category, content in rows:
    if category == "Definition" and not definition:
      definition = content
    elif category == "Keywords":
      clean_kw = content.lower().replace("keywords:", "").strip()
      keywords.append(clean_kw)

  if not definition:
    definition = (
        "A computer system is an electronic device that accepts data, processes"
        " it, stores it, and produces output information."
    )

  return definition, ", ".join(keywords)


def ask_ollama(system_prompt, user_prompt, model_name=OLLAMA_MODEL):
  """Sends prompt to local Ollama instance running offline."""
  url = "http://localhost:11434/api/generate"

  payload = {
      "model": model_name,
      "prompt": f"{system_prompt}\n\nUser Question/Attempt: {user_prompt}",
      "stream": False,
  }

  data = json.dumps(payload).encode("utf-8")
  req = urllib.request.Request(
      url, data=data, headers={"Content-Type": "application/json"}
  )

  try:
    with urllib.request.urlopen(req, timeout=45) as response:
      result = json.loads(response.read().decode("utf-8"))
      return result.get("response", "No response generated by Ollama.")
  except Exception as e:
    return (
        f"[Offline Fallback] Could not reach local Ollama engine: {e}. Make"
        " sure Ollama is running in your terminal!"
    )


def main():
  print("=" * 65)
  print("    Firemium AI: Offline RAG Tutor (Powered by Ollama)       ")
  print("=" * 65)

  # 1. Friendly Name Greeting
  raw_name = input("\nHi there! What's your name? ")
  user_name = extract_clean_name(raw_name)
  print(f"\nNice to meet you, {user_name}!")

  # 2. Country Selection
  print("\nWhich country's curriculum would you like to explore?")
  print("  1. Nigeria        [Available]")
  print("  2. USA            [Available]")
  print("  3. United Kingdom [Unavailable]")
  print("  4. Ghana          [Unavailable]")
  print("  5. Canada         [Unavailable]")

  country_input = input("\nEnter your country choice (e.g., Nigeria or USA): ").strip()
  country_clean = country_input.title()

  if "Nigeria" in country_clean or country_input == "1":
    selected_country = "Nigeria"
  elif "Usa" in country_clean or "United States" in country_clean or country_input == "2":
    selected_country = "USA"
  else:
    print(f"\nSorry {user_name}, this country's curriculum is currently unavailable.")
    return

  # 3. Education / Grade Level Input
  print(f"\nWelcome, {user_name}!")
  if selected_country == "Nigeria":
    grade_prompt = "What level of education are you currently in? (e.g., Nursery, Primary 5, Junior Secondary JS2, Senior Secondary SS1): "
  else:
    grade_prompt = "What grade level are you currently in? (e.g., Kindergarten, Elementary, Middle School, High School): "

  education_level = input(grade_prompt).strip()

  # 4. Subject Selection
  print(f"\nAwesome, {user_name}! Choose which subject you would like to explore:")
  print("  1. Computer Science [Available]")
  print("  2. Biology          [Unavailable]")
  print("  3. English          [Unavailable]")

  subject_choice = input("\nEnter subject name: ").strip().title()

  if "Computer" not in subject_choice and subject_choice != "1":
    print(f"\nSorry {user_name}, '{subject_choice}' is currently unavailable.")
    return

  # 5. Topic Notice & Database Retrieval
  print("\n" + "=" * 65)
  print("               SUBJECT: COMPUTER SCIENCE                   ")
  print("=" * 65)
  print("📌 Note: Not all topics are currently available.")
  print("   The only topic available right now is 'Computer System'.")
  print("   The rest of the topics will be updated later.\n")

  # Fetch ground truth from SQLite database
  official_def, keywords_str = get_curriculum_from_db(
      selected_country, "Computer System"
  )

  # Ask user their question
  user_question = input(f"Go ahead and ask your question, {user_name}: ").strip()

  # 6. Construct Ollama RAG System Prompt
  system_prompt = (
      f"You are Firemium AI, an offline educational tutor for students in {selected_country}.\n"
      f"The student's education level is: {education_level}.\n"
      f"Official curriculum database definition: '{official_def}'\n"
      f"Required key conceptual terms: {keywords_str}\n\n"
      f"Instructions:\n"
      f"1. Answer the student's question clearly, tailoring the tone and complexity specifically to their education level ({education_level}).\n"
      f"2. Present the core definition derived from the official database reference.\n"
      f"3. Keep it encouraging, concise, and structured."
  )

  print(f"\n🤖 [Ollama ({OLLAMA_MODEL}) is thinking and pulling from your local database offline...]\n")
  ai_response = ask_ollama(system_prompt, user_question)

  print("-" * 65)
  print("📖 OLLAMA AI TUTOR RESPONSE")
  print("-" * 65)
  print(ai_response)
  print("-" * 65)

  # 7. Interactive Student Practice & Feedback Loop
  print("\nNow it's your turn to practice!")
  user_attempt = input(
      f"Try defining 'Computer System' in your own words, {user_name}:\n> "
  ).strip()

  evaluation_prompt = (
      f"You are an encouraging teacher. A student at the {education_level} level in {selected_country} "
      f"attempted to define 'Computer System'.\n"
      f"Student's attempt: '{user_attempt}'\n"
      f"Official required keywords or concepts: {keywords_str}\n\n"
      f"Evaluate their answer gently. Tell them if they got it right, praise their phrasing, "
      f"and mention any key terms they missed, keeping it supportive and concise."
  )

  print(f"\n🤖 [Ollama ({OLLAMA_MODEL}) is reviewing your answer...]\n")
  feedback_response = ask_ollama(evaluation_prompt, user_attempt)

  print("=" * 65)
  print("🌟 TEACHER FEEDBACK")
  print("=" * 65)
  print(feedback_response)
  print("=" * 65 + "\n")


if __name__ == "__main__":
  main()